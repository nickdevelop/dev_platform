<script setup lang="ts">
// Left navigation tree: projects with their sessions (agent sessions). Multiple
// projects can stay expanded at once; each expanded project's sessions load
// independently into a per-project cache, so opening one project never clears
// another's list. Sessions are ordered by last interaction (newest first) and
// paginated per project: the list shows the newest 10 and a 「更多」 button
// appends the next 10. Search matches project names and session titles; the
// active and expanded projects always stay visible, so the open selection is
// never hidden by a filter.
import { computed, onBeforeUnmount, ref, watch } from 'vue'
import { listProjectSessions, type AgentSession } from '../../api/sessions'
import { listTaskSessionIds } from '../../api/tasks'
import { useProjectsStore } from '../../stores/projects'
import { useSessionsStore } from '../../stores/sessions'
import { UiButton, UiDialog } from '../../shared/ui'
import ProjectSessionItem from './ProjectSessionItem.vue'

const props = withDefaults(
  defineProps<{
    activeProjectId: number | null
    activeSessionId: string | null
    search: string
    showTaskSessions?: boolean
  }>(),
  {
    showTaskSessions: false,
  },
)

const emit = defineEmits<{
  // A project's settings are a workbench tab, not a page the tree navigates to.
  'open-settings': [projectId: number]
  'select-session': [projectId: number, sessionId: string]
  'new-session': [projectId: number]
  'delete-session': [projectId: number, sessionId: string]
}>()

const projectsStore = useProjectsStore()
const sessionsStore = useSessionsStore()

// Multiple projects stay expanded at once: an array (reactive) instead of a
// single id. The active project is added, never replaces the set.
const expandedIds = ref<number[]>(
  props.activeProjectId === null ? [] : [props.activeProjectId],
)

function isExpanded(projectId: number): boolean {
  return expandedIds.value.includes(projectId)
}

// Per-project session cache: each expanded project loads its own list, so lists
// never clobber each other like a single shared store list would.
const sessionsByProject = ref<Record<number, AgentSession[]>>({})
const totalByProject = ref<Record<number, number>>({})
const loadFailed = ref<Record<number, boolean>>({})
const taskSessionIds = ref<Set<string>>(new Set())

async function loadProject(projectId: number) {
  try {
    const limit = visibleCountFor(projectId)
    const [list, taskIds] = await Promise.all([
      listProjectSessions(projectId, { limit }),
      listTaskSessionIds(projectId).catch(() => []),
    ])
    sessionsByProject.value = { ...sessionsByProject.value, [projectId]: list.sessions }
    totalByProject.value = {
      ...totalByProject.value,
      [projectId]: list.total !== undefined ? list.total : list.sessions.length,
    }
    loadFailed.value = { ...loadFailed.value, [projectId]: false }
    if (taskIds && taskIds.length > 0) {
      const next = new Set(taskSessionIds.value)
      for (const id of taskIds) next.add(id)
      taskSessionIds.value = next
    }
  } catch {
    loadFailed.value = { ...loadFailed.value, [projectId]: true }
  }
}

function sessionsFor(projectId: number): AgentSession[] {
  return sessionsByProject.value[projectId] ?? []
}

// Check if a session was generated by a task.
function isTaskSession(entry: AgentSession): boolean {
  if (taskSessionIds.value.has(entry.id)) return true
  const title = entry.title || ''
  return /^\[.*(执行|确认|设计|方案|步骤)\]/.test(title) || / \(执行\)$/.test(title)
}

// The session label is driven by the turn alone: a running turn shows an
// animated marker before the name and every other state is silent. A
// disconnected session carries no badge, because opening a session re-attaches
// it — a marker there would only ask the user to fix something the platform
// already repairs.
function isRunning(entry: AgentSession): boolean {
  return entry.turn === 'running'
}

// Sessions are ordered by last interaction (the session's updated-at, which the
// backend bumps on send/continue/status change), newest first. Ties keep the
// server's creation order, because the sort below is stable.
function sortedFor(projectId: number): AgentSession[] {
  return [...sessionsFor(projectId)].sort(
    (a, b) => Date.parse(b.updatedAt) - Date.parse(a.updatedAt),
  )
}

const query = computed(() => props.search.trim().toLowerCase())

// Display fallback shared by the row and the search filter: the platform id
// must never surface as a name.
const untitledLabel = '未命名会话'

// Pagination per project: only the newest PAGE_SIZE sessions render at first;
// 「更多」 appends the next page. Counters reset when the search changes or task filter toggles.
const PAGE_SIZE = 10
const visibleCountByProject = ref<Record<number, number>>({})

function visibleCountFor(projectId: number): number {
  return visibleCountByProject.value[projectId] ?? PAGE_SIZE
}

watch([query, () => props.showTaskSessions], () => {
  visibleCountByProject.value = {}
})

function filteredFor(projectId: number): AgentSession[] {
  let sorted = sortedFor(projectId)
  if (!props.showTaskSessions) {
    sorted = sorted.filter((entry) => !isTaskSession(entry))
  }
  if (query.value === '') return sorted
  return sorted.filter((entry) =>
    (entry.title || untitledLabel).toLowerCase().includes(query.value),
  )
}

function visibleSessionsFor(projectId: number): AgentSession[] {
  return filteredFor(projectId).slice(0, visibleCountFor(projectId))
}

function hasMoreSessions(projectId: number): boolean {
  const total = totalByProject.value[projectId] ?? filteredFor(projectId).length
  return visibleSessionsFor(projectId).length < total
}

function showMoreSessions(projectId: number) {
  visibleCountByProject.value = {
    ...visibleCountByProject.value,
    [projectId]: visibleCountFor(projectId) + PAGE_SIZE,
  }
  void loadProject(projectId)
}

function canCollapseSessions(projectId: number): boolean {
  return visibleCountFor(projectId) > PAGE_SIZE
}

function collapseSessions(projectId: number) {
  visibleCountByProject.value = {
    ...visibleCountByProject.value,
    [projectId]: PAGE_SIZE,
  }
}

const visibleProjects = computed(() => {
  if (query.value === '') return projectsStore.projects
  return projectsStore.projects.filter(
    (project) =>
      project.id === props.activeProjectId ||
      isExpanded(project.id) ||
      project.name.toLowerCase().includes(query.value),
  )
})

watch(
  () => props.activeProjectId,
  (projectId) => {
    if (projectId !== null && !isExpanded(projectId)) {
      expandedIds.value = [...expandedIds.value, projectId]
    }
  },
)

watch(
  expandedIds,
  (ids) => {
    for (const projectId of ids) {
      if (!(projectId in sessionsByProject.value)) void loadProject(projectId)
    }
  },
  { immediate: true },
)

// A session created in the main pane — or deleted from it — is not in any list the
// tree holds, and the tree polls only while a turn runs. The store records every
// change it makes to the session index; each expanded project is refetched then.
watch(
  () => sessionsStore.revision,
  () => {
    for (const projectId of expandedIds.value) void loadProject(projectId)
  },
)

// The 「运行中」 label is read from the cached list, so a turn started in the
// conversation pane would never show: the tree polls a project only once its own
// list already says a session is running. When the store reports a turn starting or
// ending in the project it is showing, that project is refetched — once per
// change of turns, not once per event — and the tree's own polling carries on.
watch(
  () => sessionsStore.turnRevision,
  () => {
    if (props.activeProjectId !== null && isExpanded(props.activeProjectId)) {
      void loadProject(props.activeProjectId)
    }
  },
)

// The project tree polls only while an expanded project has a running session,
// so a project left open after an agent run finishes generates zero network
// traffic. Polling stops as soon as every running turn is done.
let pollingInterval: ReturnType<typeof setInterval> | null = null

function anyRunning(): boolean {
  for (const id of expandedIds.value) {
    if (sessionsFor(id).some(isRunning)) return true
  }
  return false
}

function startPolling() {
  if (pollingInterval !== null) return
  pollingInterval = setInterval(() => {
    for (const id of expandedIds.value) {
      if (sessionsFor(id).some(isRunning)) void loadProject(id)
    }
  }, 2000)
}

function stopPolling() {
  if (pollingInterval === null) return
  clearInterval(pollingInterval)
  pollingInterval = null
}

watch(
  () => expandedIds.value.map((id) => sessionsFor(id).map(isRunning).join(',')).join(';'),
  () => {
    if (anyRunning()) startPolling()
    else stopPolling()
  },
  { immediate: true },
)

onBeforeUnmount(stopPolling)

// Clicking a project toggles only that project; other expanded projects stay
// open. Toggling never navigates: the settings control is the only way into
// the project configuration.
function onProjectClick(projectId: number) {
  expandedIds.value = isExpanded(projectId)
    ? expandedIds.value.filter((id) => id !== projectId)
    : [...expandedIds.value, projectId]
}

function retryProject(projectId: number) {
  void loadProject(projectId)
}

const sessionToDelete = ref<{ projectId: number; session: AgentSession } | null>(null)
const deleting = ref(false)
const deleteError = ref('')

function promptDeleteSession(projectId: number, sessionId: string) {
  const session = (sessionsByProject.value[projectId] ?? []).find((s) => s.id === sessionId)
  sessionToDelete.value = {
    projectId,
    session: session ?? ({ id: sessionId, title: sessionId } as AgentSession),
  }
  deleteError.value = ''
}

function cancelDeleteSession() {
  if (deleting.value) return
  sessionToDelete.value = null
  deleteError.value = ''
}

async function confirmDeleteSession() {
  if (!sessionToDelete.value || deleting.value) return
  const { projectId, session } = sessionToDelete.value
  deleting.value = true
  deleteError.value = ''

  const success = await sessionsStore.deleteSession(projectId, session.id)
  deleting.value = false
  if (!success) {
    deleteError.value = sessionsStore.error || '删除失败，请重试。'
    return
  }

  if (sessionsByProject.value[projectId]) {
    sessionsByProject.value[projectId] = sessionsByProject.value[projectId].filter(
      (s) => s.id !== session.id,
    )
  }
  emit('delete-session', projectId, session.id)
  sessionToDelete.value = null
}
</script>

<template>
  <ul class="project-tree space-y-1 py-1 px-0.5 text-sm select-none" aria-label="项目与会话">
    <li v-for="project in visibleProjects" :key="project.id" class="project">
      <div
        class="project-row group flex items-center justify-between px-1.5 py-1.5 rounded transition-colors text-platform-text hover:bg-platform-surface-muted"
      >
        <button
          type="button"
          class="project-toggle flex items-center gap-1.5 flex-1 min-w-0 text-left outline-none cursor-pointer"
          :aria-expanded="isExpanded(project.id)"
          @click.stop="onProjectClick(project.id)"
        >
          <svg
            class="caret text-platform-text-muted w-3.5 h-3.5 transition-transform duration-150 inline-block shrink-0"
            :class="{ 'rotate-90': isExpanded(project.id) }"
            viewBox="0 0 16 16"
            fill="none"
            stroke="currentColor"
            stroke-width="1.8"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
          >
            <polyline points="6 4 10 8 6 12" />
          </svg>
          <span class="project-name truncate font-medium text-sm">{{ project.name }}</span>
        </button>

        <div class="flex items-center gap-1 shrink-0 opacity-0 group-hover:opacity-100 focus-within:opacity-100 transition-opacity">
          <button
            type="button"
            class="project-new-session w-5 h-5 flex items-center justify-center rounded hover:bg-platform-surface-muted text-platform-text-muted hover:text-platform-text transition-colors"
            :aria-label="`新建会话：${project.name}`"
            title="新建会话"
            @click.stop="emit('new-session', project.id)"
          >
            <svg viewBox="0 0 16 16" width="12" height="12" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round">
              <line x1="8" y1="3" x2="8" y2="13" />
              <line x1="3" y1="8" x2="13" y2="8" />
            </svg>
          </button>
          <button
            type="button"
            class="project-settings w-5 h-5 flex items-center justify-center rounded hover:bg-platform-surface-muted text-platform-text-muted hover:text-platform-text text-xs transition-colors"
            :aria-label="`项目设置：${project.name}`"
            title="项目设置"
            @click.stop="emit('open-settings', project.id)"
          >
            <svg viewBox="0 0 16 16" width="12" height="12" fill="none" stroke="currentColor" stroke-width="1.5">
              <circle cx="8" cy="8" r="2.5" />
              <path d="M8 1v2M8 13v2M1 8h2M13 8h2M3.05 3.05l1.41 1.41M11.54 11.54l1.41 1.41M3.05 12.95l1.41-1.41M11.54 4.46l1.41-1.41" />
            </svg>
          </button>
        </div>
      </div>

      <ul v-if="isExpanded(project.id)" class="sessions space-y-0.5 my-0.5">
        <li
          v-for="entry in visibleSessionsFor(project.id)"
          :key="entry.id"
          class="session"
          :class="{ selected: entry.id === props.activeSessionId }"
        >
          <ProjectSessionItem
            :session="entry"
            :is-selected="entry.id === props.activeSessionId"
            @select="emit('select-session', project.id, $event)"
            @delete="promptDeleteSession(project.id, $event)"
          />
        </li>
        <li v-if="loadFailed[project.id]" class="empty text-xs text-red-500 py-1">
          会话加载失败。<button type="button" class="load-more text-blue-600 underline ml-1" @click="retryProject(project.id)">重试</button>
        </li>
        <li v-else-if="sessionsFor(project.id).length === 0" class="empty text-xs text-slate-400 py-1">该项目还没有会话。</li>
        <li v-else-if="visibleSessionsFor(project.id).length === 0" class="empty text-xs text-slate-400 py-1">没有匹配的会话</li>
        <li v-if="hasMoreSessions(project.id) || canCollapseSessions(project.id)" class="pt-1 flex items-center gap-1.5">
          <button
            v-if="hasMoreSessions(project.id)"
            type="button"
            class="load-more flex-1 py-1 text-xs text-center text-slate-500 hover:text-blue-600 rounded border border-dashed border-slate-200 dark:border-slate-800 hover:border-blue-400 transition-colors"
            @click="showMoreSessions(project.id)"
          >
            更多
          </button>
          <button
            v-if="canCollapseSessions(project.id)"
            type="button"
            class="collapse-sessions flex-1 py-1 text-xs text-center text-slate-500 hover:text-blue-600 rounded border border-dashed border-slate-200 dark:border-slate-800 hover:border-blue-400 transition-colors"
            @click="collapseSessions(project.id)"
          >
            收起
          </button>
        </li>
      </ul>
    </li>
    <li v-if="projectsStore.projects.length === 0" class="empty text-xs text-slate-400 p-3 text-center">还没有项目。</li>
    <li v-else-if="visibleProjects.length === 0" class="empty text-xs text-slate-400 p-3 text-center">没有匹配的项目。</li>
  </ul>

  <!-- Delete Session Confirmation Dialog (Unified with UiDialog) -->
  <UiDialog
    v-if="sessionToDelete"
    title="删除会话"
    width-class="w-full max-w-md"
    data-test="delete-session-dialog"
    @close="cancelDeleteSession"
  >
    <div class="confirm-content flex flex-col gap-3 py-1">
      <p class="confirm-title text-sm font-medium text-platform-text">
        确定删除会话「{{ sessionToDelete.session.title || sessionToDelete.session.id }}」吗？
      </p>
      <p class="confirm-hint text-xs text-platform-text-muted">
        仅从平台列表移除；Agent 原生会话仍保留，重新扫描可能再次出现。
      </p>
      <p v-if="deleteError" class="confirm-error text-xs text-red-500" role="alert">{{ deleteError }}</p>
      <div class="confirm-actions flex items-center justify-end gap-2 pt-2">
        <UiButton variant="secondary" size="sm" class="confirm-cancel" @click="cancelDeleteSession">
          取消
        </UiButton>
        <UiButton
          variant="danger"
          size="sm"
          class="confirm-delete"
          data-test="confirm-delete"
          :disabled="deleting"
          :loading="deleting"
          @click="confirmDeleteSession"
        >
          {{ deleting ? '删除中…' : '删除' }}
        </UiButton>
      </div>
    </div>
  </UiDialog>
</template>

